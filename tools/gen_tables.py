#!/usr/bin/env python3
"""Generate src/dsp/tables.rs from the KR-106 C++ headers.

Usage: gen_tables.py <ultramaster_kr106/Source/DSP> <out.rs>

Extracts the measured lookup tables (no curve fitting here — the numbers
are copied verbatim so the Rust port reproduces the reference exactly):
  - kV4Hz[4096]       J106 VCF: 12-bit DAC code -> cutoff Hz (voice card V4)
  - kVCATableHW[256]  J106 VCA: normalized envelope -> linear gain
"""
import re
import sys
from pathlib import Path


def extract_array(text: str, name: str) -> list[str]:
    m = re.search(name + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"array {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    nums = re.findall(r"-?\d+\.\d+(?:[eE][-+]?\d+)?", body)
    return nums


def fmt(nums: list[str], per_line: int) -> str:
    lines = []
    for i in range(0, len(nums), per_line):
        lines.append("    " + ", ".join(n + "_f32" if "." in n else n for n in nums[i:i + per_line]) + ",")
    return "\n".join(lines)


def main() -> None:
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    dac = extract_array((src / "J106DACHzTable.h").read_text(), "kV4Hz")
    vca = extract_array((src / "KR106VCA.h").read_text(), "kVCATableHW")
    assert len(dac) == 4096, len(dac)
    assert len(vca) == 256, len(vca)
    out.write_text(
        "// Generated by tools/gen_tables.py from the Ultramaster KR-106 sources\n"
        "// (GPL-3.0). Do not edit by hand.\n\n"
        "/// J106 VCF cutoff (Hz) for each 12-bit DAC code, measured on voice\n"
        "/// card V4 of a real Juno-106 and gain-calibrated so code 1568 reads\n"
        "/// 248 Hz (service-manual anchor).\n"
        "#[rustfmt::skip]\n"
        f"pub static V4_HZ: [f32; 4096] = [\n{fmt(dac, 8)}\n];\n\n"
        "/// J106 VCA transfer (normalized envelope -> gain), measured with a\n"
        "/// 56-point sustain sweep and interpolated to 256 entries.\n"
        "#[rustfmt::skip]\n"
        f"pub static VCA_HW: [f32; 256] = [\n{fmt(vca, 8)}\n];\n"
    )


if __name__ == "__main__":
    main()
